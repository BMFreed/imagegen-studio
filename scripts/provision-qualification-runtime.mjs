import { promisify } from 'node:util'

import { tsImport } from 'tsx/esm/api'

const repository = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const exec = promisify(execFile)
const pythonVersion = '3.12.13'
const help = `Usage: node scripts/provision-qualification-runtime.mjs
  --app-data ABSOLUTE_NEW_ISOLATED_DIRECTORY --runtime-id UNIQUE_ID
  --managed-python ABSOLUTE_CPYTHON_3.12.13_ROOT --sdxl-config ABSOLUTE_PINNED_CONFIG
  --uv ABSOLUTE_EXECUTABLE [--report ABSOLUTE_NEW_JSON_FILE] [--activate]

Builds a non-editable worker with the locked inference extra at its final app-owned path.
Downloads dependencies when needed and starts a real Linux/NVIDIA qualification worker.
Refuses existing app data, report, runtime, Python, and active pointer paths.
This is developer qualification tooling, not a release installer or model-generation proof.
`

function argumentsFor(argv) {
  const options = { activate: false }
  const names = new Set(['app-data', 'runtime-id', 'managed-python', 'sdxl-config', 'uv', 'report'])
  for (let index = 0; index < argv.length; index++) {
    const argument = argv[index]
    if (argument === '--help') {
      return null
    }
    if (argument === '--activate' && !options.activate) {
      options.activate = true
      continue
    }
    const key = argument.slice(2)
    if (!argument.startsWith('--') || !names.has(key) || options[key] !== undefined) {
      throw new Error(`Unknown or repeated argument: ${argument}`)
    }
    const value = argv[++index]
    if (!value || value.startsWith('--')) {
      throw new Error(`Missing value for ${argument}`)
    }
    options[key] = value
  }
  for (const key of ['app-data', 'runtime-id', 'managed-python', 'sdxl-config', 'uv']) {
    if (!options[key]) {
      throw new Error(`Required argument: --${key}`)
    }
  }
  if (!/^[a-z0-9][\w.-]{0,127}$/i.test(options['runtime-id'])) {
    throw new Error('The runtime ID is invalid.')
  }
  for (const key of ['app-data', 'managed-python', 'sdxl-config', 'uv', 'report']) {
    if (
      options[key] &&
      (!path.isAbsolute(options[key]) || path.normalize(options[key]) !== options[key])
    ) {
      throw new Error(`--${key} must be an absolute normalized path.`)
    }
  }
  options.report ??= `${options['app-data']}.qualification-report.json`
  return options
}

async function absent(target) {
  try {
    await fs.lstat(target)
  } catch (error) {
    if (error.code === 'ENOENT') {
      return
    }
    throw error
  }
  throw new Error(`Refusing existing path: ${target}`)
}

async function canonicalDirectory(target) {
  const entry = await fs.lstat(target)
  if (!entry.isDirectory() || entry.isSymbolicLink() || (await fs.realpath(target)) !== target) {
    throw new Error(`Expected a canonical directory: ${target}`)
  }
}

function within(root, target) {
  const relative = path.relative(root, target)
  return (
    relative !== '' &&
    relative !== '..' &&
    !relative.startsWith(`..${path.sep}`) &&
    !path.isAbsolute(relative)
  )
}

async function sha256(file) {
  const hash = createHash('sha256')
  for await (const bytes of createReadStream(file)) {
    hash.update(bytes)
  }
  return hash.digest('hex')
}

async function treeManifest(root, { python = false } = {}) {
  const manifest = {}
  async function visit(directory) {
    for (const name of (await fs.readdir(directory)).sort()) {
      // Generated bytecode is neither wheel source nor an immutable CPython input.
      if (name === '__pycache__' || name.endsWith('.pyc')) {
        continue
      }
      const absolute = path.join(directory, name)
      const relative = path.relative(root, absolute).split(path.sep).join('/')
      const entry = await fs.lstat(absolute)
      if (entry.isSymbolicLink()) {
        const link = await fs.readlink(absolute)
        if (!python || path.isAbsolute(link) || !within(root, await fs.realpath(absolute))) {
          throw new Error(`Unsafe input symlink: ${absolute}`)
        }
        manifest[relative] = { symlink: link }
      } else if (entry.isDirectory()) {
        await visit(absolute)
      } else if (entry.isFile()) {
        manifest[relative] = { bytes: entry.size, sha256: await sha256(absolute) }
      } else {
        throw new Error(`Unsafe input entry: ${absolute}`)
      }
    }
  }
  await canonicalDirectory(root)
  await visit(root)
  return manifest
}

function equalManifest(actual, expected, description) {
  if (JSON.stringify(actual) !== JSON.stringify(expected)) {
    throw new Error(`${description} changed during capture or provisioning.`)
  }
}

function commandEnvironment(roots) {
  // Do not inherit UV/PIP/PYTHON/VIRTUAL_ENV or index overrides from the invoking shell.
  return {
    LANG: 'C.UTF-8',
    LC_ALL: 'C.UTF-8',
    PATH: '/usr/bin:/bin',
    UV_CACHE_DIR: roots.uvCacheDir,
    UV_PYTHON_DOWNLOADS: 'never',
    UV_PROJECT_ENVIRONMENT: roots.environmentRoot,
  }
}

async function runLogged(executable, argv, cwd, environment, logPath, signal) {
  const log = createWriteStream(logPath, { flags: 'a', mode: 0o600 })
  const child = spawn(executable, argv, {
    cwd,
    env: environment,
    stdio: ['ignore', 'pipe', 'pipe'],
  })
  child.stdout.pipe(log, { end: false })
  child.stderr.pipe(log, { end: false })
  let killTimer
  const abort = () => {
    child.kill('SIGTERM')
    killTimer = setTimeout(() => child.kill('SIGKILL'), 5_000)
  }
  signal.addEventListener('abort', abort, { once: true })
  if (signal.aborted) {
    abort()
  }
  try {
    await new Promise((resolve, reject) => {
      child.once('error', reject)
      child.once('close', (code, exitSignal) => {
        if (code === 0 && !signal.aborted) {
          resolve()
        } else {
          reject(
            new Error(
              `Provision command failed (${code ?? exitSignal}): ${path.basename(executable)} ${argv[0]}; see ${logPath}`,
            ),
          )
        }
      })
      log.once('error', (error) => {
        abort()
        child.once('close', () => reject(error))
      })
    })
  } finally {
    signal.removeEventListener('abort', abort)
    clearTimeout(killTimer)
    await new Promise((resolve) => log.end(resolve))
  }
}

const installedInspection = `import hashlib, importlib.metadata, json, pathlib, platform, sys
import imagegen_worker
root = pathlib.Path(imagegen_worker.__file__).resolve().parent
distribution = importlib.metadata.distribution('imagegen-worker')
direct = json.loads(distribution.read_text('direct_url.json') or '{}')
print(json.dumps({'pythonVersion': platform.python_version(), 'prefix': sys.prefix,
 'basePrefix': sys.base_prefix, 'workerRoot': str(root), 'editable': direct.get('dir_info', {}).get('editable', False),
 'packages': {d.metadata['Name']: d.version for d in importlib.metadata.distributions()},
 'workerFiles': {str(p.relative_to(root)): {'bytes': p.stat().st_size, 'sha256': hashlib.sha256(p.read_bytes()).hexdigest()}
  for p in sorted(root.rglob('*')) if p.is_file() and '__pycache__' not in p.parts and p.suffix != '.pyc'}}))`

async function provision(options) {
  if (process.platform !== 'linux' || process.arch !== 'x64') {
    throw new Error('Qualification provisioning supports Linux x64 only.')
  }
  const appData = options['app-data']
  await canonicalDirectory(path.dirname(appData))
  await canonicalDirectory(path.dirname(options.report))
  await absent(appData)
  await absent(options.report)
  if (within(appData, options.report)) {
    throw new Error('The durable report must be outside the new app-data tree.')
  }
  await canonicalDirectory(options['managed-python'])
  await canonicalDirectory(options['sdxl-config'])
  if ((await fs.realpath(options.uv)) !== options.uv || !(await fs.stat(options.uv)).isFile()) {
    throw new Error('The uv executable must be an existing canonical file.')
  }
  const controller = new AbortController()
  const interrupt = () => controller.abort()
  process.once('SIGINT', interrupt)
  process.once('SIGTERM', interrupt)
  const report = {
    boundary:
      'Developer qualification provisioning with online locked dependency installation, installed non-editable worker, pinned offline loader config and actual worker ready/confirmed exit. Not a signed/offline release artifact, installer, relocation or trained model inference qualification.',
    startedAt: new Date().toISOString(),
    status: 'preparing',
    activateRequested: options.activate,
    appData,
    runtimeId: options['runtime-id'],
    inputs: {},
  }
  let roots, ownedPython, ownedEnvironment, workspace, worker, workerModule
  const ownedPaths = []
  let activated = false
  let exitConfirmed = true
  try {
    const metadataEnvironment = { LANG: 'C.UTF-8', LC_ALL: 'C.UTF-8', PATH: '/usr/bin:/bin' }
    const sourcePython = path.join(options['managed-python'], 'bin', 'python3.12')
    if (!within(options['managed-python'], await fs.realpath(sourcePython))) {
      throw new Error('The managed Python executable escapes its distribution.')
    }
    const metadata = JSON.parse(
      (
        await exec(
          sourcePython,
          [
            '-I',
            '-c',
            'import json,platform,sys; print(json.dumps({"version":platform.python_version(),"prefix":sys.base_prefix}))',
          ],
          { env: metadataEnvironment, timeout: 30_000 },
        )
      ).stdout,
    )
    if (metadata.version !== pythonVersion || metadata.prefix !== options['managed-python']) {
      throw new Error(
        'The selected source must be a standalone managed CPython 3.12.13 distribution.',
      )
    }
    const project = path.join(repository, 'worker-python')
    report.inputs = {
      python: {
        source: options['managed-python'],
        files: await treeManifest(options['managed-python'], { python: true }),
      },
      config: { source: options['sdxl-config'], files: await treeManifest(options['sdxl-config']) },
      worker: {
        files: await treeManifest(path.join(project, 'src')),
        pyprojectSha256: await sha256(path.join(project, 'pyproject.toml')),
        lockSha256: await sha256(path.join(project, 'uv.lock')),
      },
      uv: {
        executable: options.uv,
        sha256: await sha256(options.uv),
        version: (
          await exec(options.uv, ['--version'], { env: metadataEnvironment, timeout: 30_000 })
        ).stdout.trim(),
      },
    }
    // mkdir without recursive is the ownership boundary: existing normal user data is never touched.
    await fs.mkdir(appData, { mode: 0o700 })
    const runtimeModule = await tsImport('../src/main/runtime/index.ts', import.meta.url)
    roots = await runtimeModule.createRuntimeRoots(appData)
    ownedEnvironment = path.join(roots.environmentsDir, options['runtime-id'])
    ownedPython = path.join(roots.pythonDir, `${options['runtime-id']}-cpython-${pythonVersion}`)
    await absent(roots.pointerFile)
    await absent(ownedEnvironment)
    await absent(ownedPython)
    await fs.mkdir(ownedPython, { mode: 0o700 })
    ownedPaths.push(ownedPython)
    await fs.cp(options['managed-python'], ownedPython, {
      recursive: true,
      verbatimSymlinks: true,
      force: false,
      errorOnExist: false,
    })
    equalManifest(
      await treeManifest(ownedPython, { python: true }),
      report.inputs.python.files,
      'Captured CPython',
    )
    workspace = await fs.mkdtemp(path.join(roots.downloadsDir, 'worker-build-'))
    ownedPaths.push(workspace)
    await fs.cp(path.join(project, 'src'), path.join(workspace, 'src'), {
      recursive: true,
      force: false,
      errorOnExist: true,
    })
    for (const name of ['pyproject.toml', 'uv.lock']) {
      await fs.copyFile(
        path.join(project, name),
        path.join(workspace, name),
        fs.constants.COPYFILE_EXCL,
      )
    }
    equalManifest(
      await treeManifest(path.join(workspace, 'src')),
      report.inputs.worker.files,
      'Captured worker source',
    )
    if (
      (await sha256(path.join(workspace, 'pyproject.toml'))) !==
        report.inputs.worker.pyprojectSha256 ||
      (await sha256(path.join(workspace, 'uv.lock'))) !== report.inputs.worker.lockSha256
    ) {
      throw new Error('Worker package metadata changed during capture.')
    }
    // Read the authoritative Python constant with stdlib AST; no project imports or ML are needed.
    const pins = JSON.parse(
      (
        await exec(
          path.join(ownedPython, 'bin', 'python3.12'),
          [
            '-I',
            '-c',
            'import ast,json,sys; tree=ast.parse(open(sys.argv[1]).read()); print(json.dumps(next(ast.literal_eval(n.value) for n in tree.body if isinstance(n,ast.AnnAssign) and isinstance(n.target,ast.Name) and n.target.id=="PINNED_SDXL_FILES")))',
            path.join(workspace, 'src', 'imagegen_worker', 'inference_config.py'),
          ],
          { env: metadataEnvironment, timeout: 30_000 },
        )
      ).stdout,
    )
    if (
      Object.keys(pins).length !== 17 ||
      Object.keys(report.inputs.config.files).length !== 17 ||
      Object.entries(pins).some(
        ([name, digest]) => report.inputs.config.files[name]?.sha256 !== digest,
      )
    ) {
      throw new Error(
        'The selected offline configuration is not the complete content-pinned 17-file snapshot.',
      )
    }
    await fs.mkdir(ownedEnvironment, { mode: 0o700 })
    ownedPaths.push(ownedEnvironment)
    const marker = path.join(ownedEnvironment, '.qualification-incomplete')
    const logPath = path.join(roots.logsDir, 'qualification-provision.log')
    report.logPath = logPath
    report.status = 'syncing'
    process.stderr.write(
      `Provisioning isolated qualification runtime; dependency output: ${logPath}\n`,
    )
    await runLogged(
      options.uv,
      [
        'venv',
        '--no-python-downloads',
        '--no-config',
        '--python',
        path.join(ownedPython, 'bin', 'python3.12'),
        ownedEnvironment,
      ],
      workspace,
      commandEnvironment({ ...roots, environmentRoot: ownedEnvironment }),
      logPath,
      controller.signal,
    )
    await fs.writeFile(marker, `${report.startedAt}\n`, { flag: 'wx', mode: 0o600 })
    await runLogged(
      options.uv,
      [
        'sync',
        '--locked',
        '--extra',
        'inference',
        '--no-dev',
        '--no-default-groups',
        '--no-editable',
        '--no-python-downloads',
        '--no-config',
        '--link-mode',
        'copy',
        '--python',
        path.join(ownedPython, 'bin', 'python3.12'),
      ],
      workspace,
      commandEnvironment({ ...roots, environmentRoot: ownedEnvironment }),
      logPath,
      controller.signal,
    )
    const pythonExecutable = path.join(ownedEnvironment, 'bin', 'python')
    if (!within(ownedPython, await fs.realpath(pythonExecutable))) {
      throw new Error(
        'The installed environment Python does not resolve inside its app-owned distribution.',
      )
    }
    const config = path.join(ownedEnvironment, 'resources', 'sdxl-config')
    await fs.mkdir(path.dirname(config), { recursive: true, mode: 0o700 })
    await fs.cp(options['sdxl-config'], config, {
      recursive: true,
      force: false,
      errorOnExist: true,
    })
    equalManifest(
      await treeManifest(config),
      report.inputs.config.files,
      'Captured offline configuration',
    )
    const environment = {
      HF_DATASETS_OFFLINE: '1',
      HF_HOME: roots.cacheDir,
      HF_HUB_OFFLINE: '1',
      IGS_SDXL_CONFIG_DIR: config,
      LANG: 'C.UTF-8',
      LC_ALL: 'C.UTF-8',
      TRANSFORMERS_OFFLINE: '1',
    }
    report.installed = JSON.parse(
      (
        await exec(pythonExecutable, ['-I', '-c', installedInspection], {
          cwd: roots.runtimeDir,
          env: environment,
          timeout: 30_000,
          maxBuffer: 2 * 1024 * 1024,
        })
      ).stdout,
    )
    if (
      report.installed.pythonVersion !== pythonVersion ||
      report.installed.prefix !== ownedEnvironment ||
      report.installed.basePrefix !== ownedPython ||
      report.installed.editable ||
      !within(ownedEnvironment, report.installed.workerRoot)
    ) {
      throw new Error(
        'The installed worker is not isolated non-editable app-owned CPython 3.12.13.',
      )
    }
    equalManifest(
      report.installed.workerFiles,
      await treeManifest(path.join(workspace, 'src', 'imagegen_worker')),
      'Installed worker wheel payload',
    )
    await fs.rm(workspace, { recursive: true })
    workspace = undefined
    report.status = 'qualifying'
    if (controller.signal.aborted) {
      throw new Error('Qualification provisioning was interrupted before worker startup.')
    }
    const capabilities = await tsImport(
      '../src/shared/projects/inference-worker-capabilities.ts',
      import.meta.url,
    )
    workerModule = await tsImport(
      '../src/main/projects/generation-worker-client.ts',
      import.meta.url,
    )
    exitConfirmed = false
    worker = await workerModule.GenerationWorkerClient.start(
      { pythonExecutable, runtimeRoot: roots.runtimeDir, scratchBasePath: roots.downloadsDir },
      { environment },
    )
    report.ready = structuredClone(worker.ready)
    if (
      !capabilities.isQualifiedInferenceWorkerReady(report.ready) ||
      !capabilities.supportsInferenceAnima(report.ready) ||
      !capabilities.supportsInferenceOutpaint(report.ready) ||
      !capabilities.supportsInferenceAnimaOutpaint(report.ready)
    ) {
      throw new Error(
        'The installed worker did not qualify Illustrious, original Anima and both explicit outpaint capabilities.',
      )
    }
    await worker.close()
    worker = undefined
    exitConfirmed = true
    report.confirmedWorkerExit = true
    await fs.unlink(marker)
    report.pythonExecutable = pythonExecutable
    if (options.activate) {
      if (controller.signal.aborted) {
        throw new Error('Qualification provisioning was interrupted before activation.')
      }
      const temporaryPointer = path.join(
        roots.runtimeDir,
        `.qualification-pointer-${randomUUID()}.json`,
      )
      const handle = await fs.open(temporaryPointer, 'wx', 0o600)
      try {
        await handle.writeFile(
          `${JSON.stringify({ schemaVersion: 1, runtimeId: options['runtime-id'], pythonExecutable })}\n`,
        )
        await handle.sync()
      } finally {
        await handle.close()
      }
      try {
        // A hard link publishes the complete file atomically and refuses a concurrently made pointer.
        await fs.link(temporaryPointer, roots.pointerFile)
        activated = true
      } finally {
        await fs.unlink(temporaryPointer)
      }
      const directory = await fs.open(roots.runtimeDir, 'r')
      try {
        await directory.sync()
      } finally {
        await directory.close()
      }
    }
    report.status = activated ? 'activated-qualified' : 'unpublished-qualified'
    if (activated) {
      await fs.writeFile(
        path.join(appData, 'qualification-runtime.json'),
        `${JSON.stringify({ status: 'passed', appData, runtimeId: options['runtime-id'], report: options.report, pythonExecutable, confirmedWorkerExit: true })}\n`,
        { flag: 'wx', mode: 0o600 },
      )
    }
  } catch (error) {
    report.status = 'failed'
    report.error = error.message
    if (worker) {
      try {
        await worker.close()
        exitConfirmed = true
      } catch (closeError) {
        report.exitError = closeError.message
      }
    } else if (workerModule && !exitConfirmed) {
      exitConfirmed = await workerModule.GenerationWorkerClient.retryUnconfirmedStartExit().catch(
        () => false,
      )
    }
    report.confirmedWorkerExit = exitConfirmed
    report.activated = activated
    if (!activated && exitConfirmed) {
      for (const owned of ownedPaths.toReversed()) {
        await fs.rm(owned, { recursive: true, force: true })
      }
      report.cleanup =
        "Removed only this run's unpublished environment, Python and build workspace; retained isolated logs/cache."
    } else {
      report.cleanup =
        'Retained owned runtime because activation completed or worker exit was not confirmed.'
    }
    throw error
  } finally {
    report.finishedAt = new Date().toISOString()
    await fs.writeFile(options.report, `${JSON.stringify(report, null, 2)}\n`, {
      flag: 'wx',
      mode: 0o600,
    })
    process.stderr.write(`Qualification report: ${options.report}\n`)
    process.removeListener('SIGINT', interrupt)
    process.removeListener('SIGTERM', interrupt)
  }
  process.stdout.write(
    `${JSON.stringify({ status: report.status, appData, pythonExecutable: report.pythonExecutable, report: options.report })}\n`,
  )
}

try {
  const options = argumentsFor(process.argv.slice(2))
  if (options) {
    await provision(options)
  } else {
    process.stdout.write(help)
  }
} catch (error) {
  process.stderr.write(`${error.message}\n`)
  process.exitCode = 1
}

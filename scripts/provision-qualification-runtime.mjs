/**
 * Opt-in Linux/NVIDIA qualification provisioning, not the production runtime installer. It may
 * download locked dependencies and performs a real CUDA worker startup. Invoke explicitly:
 *
 * Node scripts/provision-qualification-runtime.mjs --app-data /absolute/new/isolated/app-data
 * --runtime-id qualification-unique --managed-python /absolute/cpython-3.12.13-distribution
 * --sdxl-config /absolute/pinned-sdxl-config --uv /absolute/uv --activate
 *
 * The venv is created at its final path. This does not qualify an offline release wheelhouse,
 * signatures, relocation, repair, or model inference. Without --activate no pointer is published.
 */

"""Regenerate the original Anima header schema against actual pinned native meta models.

Run with the qualified inference environment and imagegen_worker on PYTHONPATH.
No weight payloads, network calls, model installation or CUDA allocations are used.
"""

from __future__ import annotations

import gzip
import importlib
import importlib.metadata
import json
import re
from pathlib import Path
from typing import Any, cast

from imagegen_worker.inference_anima import (
    ANIMA_BASE_ARCHITECTURE,
    _convert_state,
    _create_native_models,
)


def generate() -> str:
    for package, expected in (
        ("torch", "2.7.1"),
        ("diffusers", "0.40.0"),
        ("transformers", "5.5.4"),
        ("accelerate", "1.14.0"),
    ):
        if importlib.metadata.version(package).split("+")[0] != expected:
            raise ValueError(f"This generator requires {package}=={expected}.")
    root = Path(__file__).resolve().parent.parent
    header = json.loads(
        gzip.decompress(
            (
                root / "src/main/models/test-fixtures/anima-base-1-header.json.gz"
            ).read_bytes()
        )
    )
    torch = cast(Any, importlib.import_module("torch"))
    diffusers = cast(Any, importlib.import_module("diffusers"))
    transformers = cast(Any, importlib.import_module("transformers"))
    accelerate = cast(Any, importlib.import_module("accelerate"))
    converters = cast(
        Any, importlib.import_module("diffusers.loaders.single_file_utils")
    )
    models = _create_native_models(
        ANIMA_BASE_ARCHITECTURE,
        torch,
        diffusers,
        transformers,
        accelerate,
    )
    state = {
        key: torch.empty(tuple(tensor["shape"]), device="meta", dtype=torch.float16)
        for key, tensor in header.items()
    }
    converted = _convert_state("checkpoint", state, converters)
    for name, actual in converted.items():
        expected = models[name].state_dict()
        if set(actual) != set(expected):
            raise ValueError(f"The {name} reference schema differs from native keys.")
        for key, tensor in actual.items():
            if tuple(tensor.shape) != tuple(expected[key].shape):
                raise ValueError(
                    f"The {name}.{key} reference shape differs from native."
                )
    shapes = {
        key.removeprefix("model.diffusion_model."): tensor["shape"]
        for key, tensor in header.items()
    }
    lines = [
        "// Generated by scripts/generate-anima-checkpoint-profile.py. Do not edit by hand.",
        "// Original Anima Base 1.0; InvokeAI 9e1540962bcca7f8fa668d7d8e02cf79d75fda3b.",
        "// Every key/shape was checked against pinned Diffusers 0.40.0 native meta models.",
        "// This describes topology only; checkpoint SHA is not an inference allowlist.",
        "export const ANIMA_BASE_1_TENSOR_SHAPES: Readonly<Record<string, readonly number[]>> = {",
    ]

    def natural_key(item: tuple[str, list[int]]) -> tuple[str | int, ...]:
        return tuple(
            int(part) if part.isdecimal() else part
            for part in re.split(r"(\d+)", item[0])
        )

    for key, shape in sorted(shapes.items(), key=natural_key):
        values = ", ".join(
            f"{value:_}" if value >= 10_000 else str(value) for value in shape
        )
        lines.append(f"  '{key}': [{values}],")
    lines.append("}")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    destination = (
        Path(__file__).resolve().parent.parent
        / "src/main/models/anima-checkpoint-profile.ts"
    )
    destination.write_text(generate())
